/*
# Add appeals table for password reset requests

1. New Tables
- `appeals`: stores member password reset requests for admin review.
  - username: the member's username
  - message: the member's explanation
  - status: pending, approved, declined, completed, superseded
  - admin_note: optional note from the admin
  - reviewed_at: when the admin acted on the request

2. Security
- RLS enabled: only authenticated users can insert (the form uses anon, so we allow anon insert).
- Admins can read and update appeals.
- Anonymous users can insert new appeals (submitting a reset request while logged out).
*/

CREATE TABLE IF NOT EXISTS public.appeals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  username text NOT NULL,
  message text NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'declined', 'completed', 'superseded')),
  admin_note text,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.appeals ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "appeals_anon_insert" ON public.appeals;
CREATE POLICY "appeals_anon_insert" ON public.appeals FOR INSERT
TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "appeals_admin_read" ON public.appeals;
CREATE POLICY "appeals_admin_read" ON public.appeals FOR SELECT TO authenticated
USING (public.is_admin());

DROP POLICY IF EXISTS "appeals_admin_update" ON public.appeals;
CREATE POLICY "appeals_admin_update" ON public.appeals FOR UPDATE TO authenticated
USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "appeals_admin_delete" ON public.appeals;
CREATE POLICY "appeals_admin_delete" ON public.appeals FOR DELETE TO authenticated
USING (public.is_admin());
